-- Each completed workout belongs to a user.
alter table public.workouts
  add column user_id uuid not null
    references auth.users(id) on delete cascade,

  add column performed_at timestamptz not null default now(),

  add column created_at timestamptz not null default now(),

  add column weight_unit text not null default 'lb'
    check (weight_unit = 'lb');

-- Reject empty or whitespace-only names.
alter table public.workouts
  add constraint workouts_name_not_blank
  check (length(trim(workout_name)) > 0);

-- Support loading a user's workouts in date order.
create index workouts_user_performed_at_idx
  on public.workouts (user_id, performed_at desc);


-- Give each exercise within a workout its own ID and position.
alter table public.workout_exercises
  add column id bigint generated by default as identity,
  add column position integer not null
    check (position > 0);

-- Use the new ID as the primary key.
-- Still prevent duplicate exercises within one workout.
alter table public.workout_exercises
  drop constraint workout_exercises_pkey,
  add constraint workout_exercises_pkey primary key (id),
  add constraint workout_exercises_unique_exercise
    unique (workout_id, exercise_id),
  add constraint workout_exercises_unique_position
    unique (workout_id, position);

-- Prevent deleting a library exercise used by saved workouts.
alter table public.workout_exercises
  drop constraint workout_exercises_exercise_id_fkey,
  add constraint workout_exercises_exercise_id_fkey
    foreign key (exercise_id)
    references public.exercises(id)
    on delete restrict;

-- Store each performed set as its own row.
create table public.workout_sets (
  id bigint generated by default as identity primary key,

  workout_exercise_id bigint not null
    references public.workout_exercises(id)
    on delete cascade,

  position integer not null
    check (position > 0),

  reps integer not null
    check (reps > 0),

  weight numeric(10, 2) not null
    check (weight between 0 and 99999999.99),

  constraint workout_sets_unique_position
    unique (workout_exercise_id, position)
);

alter table public.workout_sets
  enable row level security;

create policy "Users manage their own workout exercises"
on public.workout_exercises
for all
to authenticated
using (
  exists (
    select 1
    from public.workouts as w
    where w.id = workout_exercises.workout_id
      and w.user_id = (select auth.uid())
  )
)
with check (
  exists (
    select 1
    from public.workouts as w
    where w.id = workout_exercises.workout_id
      and w.user_id = (select auth.uid())
  )
);

-- Remove broad workout access.
drop policy if exists "allow anon read workouts"
  on public.workouts;
drop policy if exists "allow anon insert workouts"
  on public.workouts;
drop policy if exists "allow anon update workouts"
  on public.workouts;
drop policy if exists "allow anon delete workouts"
  on public.workouts;

-- Remove broad workout-exercise access.
drop policy if exists "allow anon read workout_exercises"
  on public.workout_exercises;
drop policy if exists "allow anon insert workout_exercises"
  on public.workout_exercises;
drop policy if exists "allow anon update workout_exercises"
  on public.workout_exercises;
drop policy if exists "allow anon delete workout_exercises"
  on public.workout_exercises;

-- Enable ownership checks.
alter table public.workouts enable row level security;
alter table public.workout_exercises enable row level security;

create policy "Users manage their own workouts"
on public.workouts
for all
to authenticated
using (
  user_id = (select auth.uid())
)
with check (
  user_id = (select auth.uid())
);

create policy "Users manage their own workout sets"
on public.workout_sets
for all
to authenticated
using (
  exists (
    select 1
    from public.workout_exercises as we
    join public.workouts as w
      on w.id = we.workout_id
    where we.id = workout_sets.workout_exercise_id
      and w.user_id = (select auth.uid())
  )
)
with check (
  exists (
    select 1
    from public.workout_exercises as we
    join public.workouts as w
      on w.id = we.workout_id
    where we.id = workout_sets.workout_exercise_id
      and w.user_id = (select auth.uid())
  )
);

-- Remove existing application-role privileges.
revoke all privileges on table
  public.workouts,
  public.workout_exercises,
  public.workout_sets
from anon, authenticated;

-- Signed-in users may perform these operations,
-- subject to the ownership policies above.
grant select, insert, update, delete on table
  public.workouts,
  public.workout_exercises,
  public.workout_sets
to authenticated;

-- Allow generated IDs for inserts.
revoke all privileges on sequence
  public.workouts_id_seq,
  public.workout_exercises_id_seq,
  public.workout_sets_id_seq
from anon, authenticated;

grant usage, select on sequence
  public.workouts_id_seq,
  public.workout_exercises_id_seq,
  public.workout_sets_id_seq
to authenticated;
